"""Streamlit interface for SecondsMatter.

This file only renders the page and calls the application layers in
`src/secondsmatter/`. It must not build prompts or make dispatch decisions.
"""

import streamlit as st

from secondsmatter.config import get_settings

st.set_page_config(page_title="SecondsMatter", page_icon="🚑", layout="wide")

settings = get_settings()

st.title("SecondsMatter")
st.caption("Decision-support prototype for emergency resource planning and dispatch")

# EU AI Act Art. 50: users must know they are interacting with an AI system.
st.info(
    "**You are interacting with an AI system.** Answers are generated by a "
    "language model and can be wrong. A human stays in control of every "
    "simulated decision."
)
st.warning(
    "**Academic simulation only.** SecondsMatter is a NOVA IMS student research "
    "prototype, not a real emergency dispatch system. It does not send dispatch "
    "instructions or assess clinical priority. Fleet availability is simulated. "
    "Do not enter personal or patient data."
)

with st.sidebar:
    st.subheader("Status")
    st.write(f"Model: `{settings.llm_model}`")
    if settings.has_api_key:
        st.success("Model credentials configured")
    else:
        st.error("ANTHROPIC_API_KEY is not set (see `.env.example`)")

st.chat_input("The dispatch assistant is not connected yet.", disabled=True)
